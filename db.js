import pg from 'pg';
import crypto from 'node:crypto';

// Carrega o arquivo .env (DATABASE_URL), se existir
try { process.loadEnvFile(new URL('./.env', import.meta.url)); } catch {}

const url = process.env.DATABASE_URL;
if (!url) {
  console.error(`
  ⚠  DATABASE_URL não configurada.
  Crie o arquivo .env na pasta horario-escolar (modelo em .env.example) com a "connection string" do banco.
`);
  process.exit(1);
}

const local = /localhost|127\.0\.0\.1/.test(url);
const pool = new pg.Pool({
  connectionString: url,
  ssl: local ? false : { rejectUnauthorized: false },
  max: Number(process.env.PG_POOL_MAX || 5),
});

// As queries usam "?" como parâmetro; aqui viram $1, $2... do Postgres
const converter = (sql) => { let i = 0; return sql.replace(/\?/g, () => '$' + ++i); };
function criarHelpers(exec) {
  return {
    all: async (sql, ...p) => (await exec(converter(sql), p)).rows,
    get: async (sql, ...p) => (await exec(converter(sql), p)).rows[0],
    run: async (sql, ...p) => {
      const r = await exec(converter(sql), p);
      return { changes: r.rowCount, id: r.rows[0]?.id };
    },
  };
}

export const db = criarHelpers((sql, p) => pool.query(sql, p));

export async function transacao(fn) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const r = await fn(criarHelpers((sql, p) => client.query(sql, p)));
    await client.query('COMMIT');
    return r;
  } catch (e) {
    await client.query('ROLLBACK');
    throw e;
  } finally {
    client.release();
  }
}

export function hashPassword(senha) {
  const salt = crypto.randomBytes(16).toString('hex');
  const hash = crypto.scryptSync(senha, salt, 64).toString('hex');
  return `${salt}:${hash}`;
}

export function verifyPassword(senha, armazenado) {
  const [salt, hash] = String(armazenado).split(':');
  if (!salt || !hash) return false;
  const calc = crypto.scryptSync(senha, salt, 64);
  return crypto.timingSafeEqual(calc, Buffer.from(hash, 'hex'));
}

// Prefixo "hor_" para não misturar com outras tabelas caso o banco seja compartilhado.
const TABELAS = ['hor_usuarios', 'hor_sessoes', 'hor_config', 'hor_usuario_escola', 'hor_periodos', 'hor_turmas', 'hor_disciplinas',
  'hor_professores', 'hor_indisponibilidades', 'hor_distribuicao', 'hor_aulas'];

// Sempre idempotente: pode rodar em toda inicialização.
const ESQUEMA = `
CREATE TABLE IF NOT EXISTS hor_usuarios (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           text NOT NULL,
  login          text NOT NULL,
  senha_hash     text NOT NULL,
  cargo          text,
  criado_em      timestamptz NOT NULL DEFAULT now(),
  ultimo_acesso  timestamptz,
  arquivado_em   timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS hor_usuarios_login_uidx ON hor_usuarios (lower(login));

CREATE TABLE IF NOT EXISTS hor_sessoes (
  token       text PRIMARY KEY,
  usuario_id  integer NOT NULL REFERENCES hor_usuarios(id) ON DELETE CASCADE,
  criado_em   timestamptz NOT NULL DEFAULT now()
);

-- Uma linha por escola (o id é o da escola). rede: 'particular' ou 'publica' (Lei 11.738: máx. 2/3 da jornada em sala)
CREATE TABLE IF NOT EXISTS hor_config (
  id            integer PRIMARY KEY CHECK (id = 1),
  escola        text NOT NULL DEFAULT 'Minha escola',
  rede          text NOT NULL DEFAULT 'particular' CHECK (rede IN ('particular', 'publica')),
  dias          integer[] NOT NULL DEFAULT '{1,2,3,4,5}',
  duracao_aula  integer NOT NULL DEFAULT 50 CHECK (duracao_aula BETWEEN 20 AND 120)
);
INSERT INTO hor_config (id) SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM hor_config);

-- Horários das aulas de cada turno (ex.: Manhã, 1ª aula, 07:00–07:50)
CREATE TABLE IF NOT EXISTS hor_periodos (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno   text NOT NULL CHECK (turno IN ('Manhã', 'Tarde', 'Noite')),
  inicio  text NOT NULL CHECK (inicio ~ '^[0-2][0-9]:[0-5][0-9]$'),
  fim     text NOT NULL CHECK (fim ~ '^[0-2][0-9]:[0-5][0-9]$'),
  CHECK (fim > inicio)
);

-- turno 'Integral' usa os horários da Manhã e da Tarde
CREATE TABLE IF NOT EXISTS hor_turmas (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome   text NOT NULL,
  turno  text NOT NULL CHECK (turno IN ('Manhã', 'Tarde', 'Noite', 'Integral'))
);

CREATE TABLE IF NOT EXISTS hor_disciplinas (
  id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome  text NOT NULL,
  cor   integer NOT NULL DEFAULT 0
);

-- jornada_horas: jornada semanal (usada na regra da rede pública)
-- limite_aulas: máximo de aulas por semana que a escola definiu (opcional)
CREATE TABLE IF NOT EXISTS hor_professores (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           text NOT NULL,
  jornada_horas  numeric(4,1) CHECK (jornada_horas > 0 AND jornada_horas <= 60),
  limite_aulas   integer CHECK (limite_aulas > 0 AND limite_aulas <= 80)
);

-- Dia/horário em que o professor NÃO pode dar aula. dia: 1 = segunda ... 6 = sábado
CREATE TABLE IF NOT EXISTS hor_indisponibilidades (
  professor_id  integer NOT NULL REFERENCES hor_professores(id) ON DELETE CASCADE,
  dia           integer NOT NULL CHECK (dia BETWEEN 1 AND 6),
  periodo_id    integer NOT NULL REFERENCES hor_periodos(id) ON DELETE CASCADE,
  PRIMARY KEY (professor_id, dia, periodo_id)
);

-- Quem dá qual disciplina em qual turma, e quantas aulas por semana
CREATE TABLE IF NOT EXISTS hor_distribuicao (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turma_id       integer NOT NULL REFERENCES hor_turmas(id) ON DELETE CASCADE,
  disciplina_id  integer NOT NULL REFERENCES hor_disciplinas(id) ON DELETE CASCADE,
  professor_id   integer NOT NULL REFERENCES hor_professores(id) ON DELETE CASCADE,
  aulas_semana   integer NOT NULL CHECK (aulas_semana BETWEEN 1 AND 40),
  UNIQUE (turma_id, disciplina_id)
);

-- A grade: cada célula (turma, dia, horário) aponta para uma linha da distribuição.
-- Trocar o professor na distribuição troca em todas as aulas de uma vez.
CREATE TABLE IF NOT EXISTS hor_aulas (
  turma_id         integer NOT NULL REFERENCES hor_turmas(id) ON DELETE CASCADE,
  dia              integer NOT NULL CHECK (dia BETWEEN 1 AND 6),
  periodo_id       integer NOT NULL REFERENCES hor_periodos(id) ON DELETE CASCADE,
  distribuicao_id  integer NOT NULL REFERENCES hor_distribuicao(id) ON DELETE CASCADE,
  PRIMARY KEY (turma_id, dia, periodo_id)
);
CREATE INDEX IF NOT EXISTS hor_aulas_dist_idx ON hor_aulas (distribuicao_id);

-- Gerador automático e regras extras
-- fixa: a coordenação travou esta aula; o gerador e as sugestões nunca mexem nela
ALTER TABLE hor_aulas ADD COLUMN IF NOT EXISTS fixa boolean NOT NULL DEFAULT false;
-- máximo de aulas da mesma disciplina no mesmo dia, na mesma turma
ALTER TABLE hor_config ADD COLUMN IF NOT EXISTS max_disc_dia integer NOT NULL DEFAULT 2 CHECK (max_disc_dia BETWEEN 1 AND 10);
-- quando a disciplina tiver 2 aulas no mesmo dia, preferir que fiquem seguidas (aula dupla)
ALTER TABLE hor_config ADD COLUMN IF NOT EXISTS preferir_duplas boolean NOT NULL DEFAULT false;
-- máximo de aulas por dia para o professor (opcional)
ALTER TABLE hor_professores ADD COLUMN IF NOT EXISTS max_aulas_dia integer CHECK (max_aulas_dia BETWEEN 1 AND 20);

-- Várias escolas: hor_config vira o cadastro das escolas (antes era uma linha só, id = 1)
ALTER TABLE hor_config DROP CONSTRAINT IF EXISTS hor_config_id_check;
CREATE SEQUENCE IF NOT EXISTS hor_config_id_seq OWNED BY hor_config.id;
SELECT setval('hor_config_id_seq', GREATEST((SELECT max(id) FROM hor_config), 1));
ALTER TABLE hor_config ALTER COLUMN id SET DEFAULT nextval('hor_config_id_seq');
ALTER TABLE hor_config ADD COLUMN IF NOT EXISTS criado_em timestamptz NOT NULL DEFAULT now();

-- Quem acessa cada escola (o mesmo coordenador pode ter várias)
CREATE TABLE IF NOT EXISTS hor_usuario_escola (
  usuario_id  integer NOT NULL REFERENCES hor_usuarios(id) ON DELETE CASCADE,
  escola_id   integer NOT NULL REFERENCES hor_config(id) ON DELETE CASCADE,
  PRIMARY KEY (usuario_id, escola_id)
);
CREATE INDEX IF NOT EXISTS hor_usuario_escola_escola_idx ON hor_usuario_escola (escola_id);
-- Na primeira vez, quem já existia ganha acesso às escolas que já existiam
INSERT INTO hor_usuario_escola (usuario_id, escola_id)
  SELECT u.id, c.id FROM hor_usuarios u CROSS JOIN hor_config c
  WHERE NOT EXISTS (SELECT 1 FROM hor_usuario_escola);

-- Cada cadastro pertence a uma escola. Os dados que já existiam ficam na escola 1.
${['hor_periodos', 'hor_turmas', 'hor_disciplinas', 'hor_professores'].map((t) => `ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS escola_id integer NOT NULL DEFAULT 1 REFERENCES hor_config(id) ON DELETE CASCADE;
ALTER TABLE ${t} ALTER COLUMN escola_id DROP DEFAULT;
CREATE INDEX IF NOT EXISTS ${t}_escola_idx ON ${t} (escola_id);`).join('\n')}
-- Nomes repetidos só são proibidos dentro da mesma escola
DROP INDEX IF EXISTS hor_turmas_nome_uidx;
DROP INDEX IF EXISTS hor_disciplinas_nome_uidx;
CREATE UNIQUE INDEX IF NOT EXISTS hor_turmas_escola_nome_uidx ON hor_turmas (escola_id, lower(nome));
CREATE UNIQUE INDEX IF NOT EXISTS hor_disciplinas_escola_nome_uidx ON hor_disciplinas (escola_id, lower(nome));

-- Segurança: RLS ligado e sem políticas. A API pública do Supabase (chave anon)
-- não lê nada; só este servidor, que conecta direto no banco.
${TABELAS.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}
`;

async function popularExemplo() {
  await transacao(async (q) => {
    const id = (r) => r.id;
    const u = id(await q.run(`INSERT INTO hor_usuarios (nome, login, senha_hash, cargo) VALUES (?, ?, ?, ?) RETURNING id`,
      'Coordenação Pedagógica', 'coordenacao@escola.com', hashPassword('123456'), 'Coordenadora'));
    const E = (await q.get('SELECT min(id) AS id FROM hor_config')).id;
    await q.run(`UPDATE hor_config SET escola = 'Escola Exemplo' WHERE id = ?`, E);
    await q.run('INSERT INTO hor_usuario_escola (usuario_id, escola_id) VALUES (?, ?)', u, E);

    const per = [];
    for (const [i, f] of [['07:00', '07:50'], ['07:50', '08:40'], ['08:40', '09:30'], ['09:50', '10:40'], ['10:40', '11:30']]) {
      per.push(id(await q.run('INSERT INTO hor_periodos (escola_id, turno, inicio, fim) VALUES (?, ?, ?, ?) RETURNING id', E, 'Manhã', i, f)));
    }
    for (const [i, f] of [['13:00', '13:50'], ['13:50', '14:40'], ['14:40', '15:30'], ['15:50', '16:40'], ['16:40', '17:30']]) {
      await q.run('INSERT INTO hor_periodos (escola_id, turno, inicio, fim) VALUES (?, ?, ?, ?)', E, 'Tarde', i, f);
    }

    const turma = async (n, t) => id(await q.run('INSERT INTO hor_turmas (escola_id, nome, turno) VALUES (?, ?, ?) RETURNING id', E, n, t));
    const t6 = await turma('6º Ano A', 'Manhã');
    const t7 = await turma('7º Ano A', 'Manhã');

    const disc = {};
    for (const [i, n] of ['Português', 'Matemática', 'Ciências', 'História', 'Geografia', 'Inglês', 'Arte', 'Educação Física'].entries()) {
      disc[n] = id(await q.run('INSERT INTO hor_disciplinas (escola_id, nome, cor) VALUES (?, ?, ?) RETURNING id', E, n, i));
    }

    const prof = async (n, j, l) => id(await q.run('INSERT INTO hor_professores (escola_id, nome, jornada_horas, limite_aulas) VALUES (?, ?, ?, ?) RETURNING id', E, n, j, l));
    const ana = await prof('Ana Ribeiro', 20, 12);
    const bruno = await prof('Bruno Costa', 20, 12);
    const carla = await prof('Carla Mendes', 20, 10);
    const davi = await prof('Davi Nunes', 20, 10);
    const elisa = await prof('Elisa Prado', 10, 6);
    await q.run('INSERT INTO hor_indisponibilidades (professor_id, dia, periodo_id) VALUES (?, 5, ?), (?, 5, ?)', elisa, per[3], elisa, per[4]);

    const dist = async (t, d, p, n) => id(await q.run(
      'INSERT INTO hor_distribuicao (turma_id, disciplina_id, professor_id, aulas_semana) VALUES (?, ?, ?, ?) RETURNING id', t, disc[d], p, n));
    for (const t of [t6, t7]) {
      await dist(t, 'Português', ana, 5);
      await dist(t, 'Matemática', bruno, 5);
      await dist(t, 'Ciências', carla, 3);
      await dist(t, 'História', davi, 3);
      await dist(t, 'Geografia', davi, 2);
      await dist(t, 'Inglês', elisa, 2);
      await dist(t, 'Arte', carla, 2);
      await dist(t, 'Educação Física', elisa, 2);
    }
    // Começa a grade do 6º Ano A na segunda-feira, para mostrar como fica
    const ds = await q.all('SELECT d.id, x.nome FROM hor_distribuicao d JOIN hor_disciplinas x ON x.id = d.disciplina_id WHERE turma_id = ?', t6);
    const de = Object.fromEntries(ds.map((d) => [d.nome, d.id]));
    for (const [i, n] of ['Português', 'Português', 'Matemática', 'Ciências', 'História'].entries()) {
      await q.run('INSERT INTO hor_aulas (turma_id, dia, periodo_id, distribuicao_id) VALUES (?, 1, ?, ?)', t6, per[i], de[n]);
    }
  });
  console.log('Banco vazio: dados de exemplo criados.');
}

export async function iniciarBanco() {
  await pool.query(ESQUEMA);
  const { total } = await db.get('SELECT COUNT(*)::int AS total FROM hor_usuarios');
  if (total === 0) await popularExemplo();
}
